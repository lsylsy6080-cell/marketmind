BEGIN;
CREATE TABLE IF NOT EXISTS public.funding_snapshots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol text NOT NULL,
 fetched_at timestamptz NOT NULL,
 funding_time timestamptz,
 next_funding_time timestamptz,
 funding_rate numeric NOT NULL,
 funding_rate_percent numeric NOT NULL,
 annualized_rate_percent numeric NOT NULL,
 mark_price numeric NOT NULL,
 index_price numeric NOT NULL,
 score numeric NOT NULL,
 confidence numeric NOT NULL,
 direction text NOT NULL,
 risk_level text NOT NULL,
 trading_permission text NOT NULL,
 score_details jsonb NOT NULL DEFAULT '{}'::jsonb,
 strategy_version text NOT NULL
);
CREATE INDEX IF NOT EXISTS funding_snapshots_symbol_latest_idx
 ON public.funding_snapshots(symbol,fetched_at DESC);
COMMIT;
