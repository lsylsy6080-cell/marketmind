BEGIN;
CREATE TABLE IF NOT EXISTS public.technical_snapshots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 exchange text NOT NULL, market_type text NOT NULL, symbol text NOT NULL,
 timeframe text NOT NULL, candle_open_time timestamptz NOT NULL,
 analyzed_at timestamptz NOT NULL,
 close_price numeric NOT NULL,
 ema_20 numeric, ema_60 numeric, ema_120 numeric, ema_240 numeric,
 rsi_14 numeric, macd numeric, macd_signal numeric, macd_histogram numeric,
 atr_14 numeric, adx_14 numeric, bollinger_upper numeric, bollinger_middle numeric,
 bollinger_lower numeric, bollinger_width numeric, volume_ma_20 numeric,
 volume_ratio numeric, obv numeric, mfi_14 numeric,
 market_structure text, trend_direction text, momentum_direction text,
 volatility_state text, indicator_data jsonb NOT NULL DEFAULT '{}'::jsonb,
 CONSTRAINT technical_snapshots_candle_unique UNIQUE(exchange,market_type,symbol,timeframe,candle_open_time)
);
CREATE INDEX IF NOT EXISTS technical_snapshots_latest_idx
 ON public.technical_snapshots(symbol,timeframe,candle_open_time DESC);
CREATE TABLE IF NOT EXISTS public.market_scores (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol text NOT NULL, analyzed_at timestamptz NOT NULL,
 market_regime text, direction text,
 total_score numeric, confidence numeric, trend_score numeric,
 momentum_score numeric, volume_score numeric, structure_score numeric,
 volatility_score numeric, derivatives_score numeric,
 trading_permission text, risk_level text,
 strategy_version text NOT NULL, score_details jsonb NOT NULL DEFAULT '{}'::jsonb,
 CONSTRAINT market_scores_unique UNIQUE(symbol,strategy_version,analyzed_at)
);
CREATE INDEX IF NOT EXISTS market_scores_latest_idx
 ON public.market_scores(symbol,analyzed_at DESC);
COMMIT;
